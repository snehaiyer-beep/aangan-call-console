import { estimateTimes } from "./policy";
import type {
  CallLead,
  CriterionKey,
  CriterionResult,
  CriterionStatus,
  DossierEntity,
  LeadDossier,
  Qualification,
  Speaker,
} from "./types";

type Line = [Speaker, string, string[]?];

interface SeedDef {
  id: string;
  callerName: string | null;
  receivedAt: string;
  durationSec: number;
  source?: string;
  qualification: Qualification;
  qualificationReason: string;
  flags?: string[];
  assignedDesignerId?: string | null;
  dossier: LeadDossier;
  criteria: Record<CriterionKey, CriterionResult>;
  lines: Line[];
}

const c = (status: CriterionStatus, note: string): CriterionResult => ({ status, note });
const e = (value: string, note?: string): DossierEntity => ({ value, note });
const NA = (note: string): Record<CriterionKey, CriterionResult> => ({
  realProject: c("unclear", note),
  serviceArea: c("unclear", note),
  timeline: c("unclear", note),
  budget: c("unclear", note),
  decisionMaker: c("unclear", note),
});

function build(def: SeedDef): CallLead {
  const timed = estimateTimes(
    def.lines.map(([speaker, text, extracted]) => ({ speaker, text, extracted })),
    Math.max(def.durationSec, 1),
  );
  return {
    id: def.id,
    reference: `SEP26-${def.id}`,
    callerName: def.callerName,
    phone: null,
    receivedAt: def.receivedAt,
    durationSec: def.durationSec,
    handledBy: "Front Desk",
    source: def.source,
    qualification: def.qualification,
    qualificationReason: def.qualificationReason,
    flags: def.flags ?? [],
    assignedDesignerId: def.assignedDesignerId ?? null,
    dossier: def.dossier,
    criteria: def.criteria,
    transcript: timed.map((t, i) => ({ id: `${def.id}-${i + 1}`, ...t })),
  };
}

